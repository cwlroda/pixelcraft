//! A tiny 5×7 bitmap font rendered as solid UI quads. Enough for HUD counts,
//! a clock, block names and quest objectives. Each glyph is seven rows; the low
//! five bits of each row are the pixels (bit 4 = leftmost).

/// Glyph width/height in source pixels.
pub const GLYPH_W: u32 = 5;
pub const GLYPH_H: u32 = 7;

