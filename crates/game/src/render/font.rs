/// Pixel width of `text` at the given pixel scale (1 source px → `scale` px),
/// including 1-pixel inter-glyph spacing.
pub fn text_width(text: &str, scale: f32) -> f32 {
    let glyphs = text.chars().count() as f32;
    if glyphs == 0.0 {
        0.0
    } else {
        (glyphs * (GLYPH_W as f32 + 1.0) - 1.0) * scale
    }
}
